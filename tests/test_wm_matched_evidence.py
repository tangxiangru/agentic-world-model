def test_correctness_is_not_self_generation_or_exclusive_purity():
    result = flags(example(source="external answer-verified samples"))
    assert result["correctness_selection"] is True
    assert result["self_sampled"] is None
    mixed = flags(example(source="self-generated; keep correct samples; include wrong attempts"))
    assert mixed["self_sampled"] is mixed["correctness_selection"] is mixed["wrong_attempts"] is True


