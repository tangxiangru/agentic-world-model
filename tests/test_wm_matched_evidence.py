def test_outcomes_rawtext_code_and_nondata_plan_fields_never_forwarded():
    value = example(source="CANARY 0.987654321 answer-verified source /PRIVATE/path")
    value.update(example_id="SECRET_ID", accuracy=0.456789, parent={"accuracy": 0.543219})
    value["model_input"]["plan"].update(result={"accuracy": 0.777888}, analysis="self-generated")
    value["model_input"]["plan"]["setup"]["method"]["target_format"] = "teacher-generated"
    value["model_input"]["code"] = [{"role": "data_builder_0", "status": "reconstructed", "content": "# self-generated\nwrong_frac = 0.9"}]
    encoded = json.dumps(evidence.extract(value))
    assert not any(token in encoded for token in ("CANARY", "987654321", "PRIVATE", "SECRET_ID", "456789", "543219", "777888"))
    result = flags(value)
    assert result["correctness_selection"] is True
    assert result["self_sampled"] is result["teacher_generated"] is result["wrong_attempts"] is None


def test_only_immediate_screened_parent_not_current_or_older_backfill():
    value = example(source="teacher-generated")
    older = example(source="self-generated")["model_input"]
    value["history"] = [{"recipe_status": "screened", "model_input": older},
                        {"recipe_status": "quarantined", "model_input": older}]
    result = evidence.extract(value)["context"]
    assert result["current"]["evidence"]["teacher_generated"] is True
    assert result["immediate_parent"]["status"] == "quarantined"
    assert all(v is None for v in result["immediate_parent"]["evidence"].values())
    value["history"][-1] = {"recipe_status": "screened", "model_input": older}
    assert flags(value, "immediate_parent")["self_sampled"] is True
    assert flags(value, "immediate_parent")["teacher_generated"] is None


def test_extraction_does_not_mutate_input_and_provenance_is_separate():
    value = example(source="self-generated plus gold GSM8K train")
    before = copy.deepcopy(value)
    result = evidence.extract(value)
    assert value == before
    assert "sha256" not in json.dumps(result["context"])
    assert result["provenance"]["current"]["fields"][0]["sha256"]


def test_missing_current_and_unknown_parent_status():
    result = evidence.extract({"history": [{"recipe_status": "unscreened", "model_input": example()["model_input"]}]})
    assert result["context"]["current"]["status"] == "missing_recipe"
    assert result["context"]["immediate_parent"]["status"] == "missing_recipe"


def test_validate_context_accepts_only_canonical_output_without_mutation():
    context = evidence.extract(example(source="self-generated"))["context"]
    before = copy.deepcopy(context)
    assert evidence.validate_context(context) == before
    assert context == before


@pytest.mark.parametrize("mutation", [
    lambda x: x.update(accuracy=0.9),
    lambda x: x.update(schema="unknown"),
    lambda x: x["current"].update(raw_source="private data"),
    lambda x: x["current"].update(status="invented"),
    lambda x: x["current"].update(family_tokens=["sft", "sft"]),
    lambda x: x["current"].update(family_tokens=["sft", "rft"]),
    lambda x: x["current"].update(family_tokens=["SECRET"]),
    lambda x: x["current"].update(family_tokens=[0.987]),
    lambda x: x["current"].update(family_tokens=["grpo"]),
    lambda x: x["current"].update(objective="unknown"),
    lambda x: x["current"]["evidence"].update(accuracy=0.8),
    lambda x: x["current"]["evidence"].update(self_sampled=False),
    lambda x: x["current"]["evidence"].update(self_sampled=1),
    lambda x: x["current"]["evidence"].update(self_sampled="true"),
    lambda x: x["immediate_parent"]["evidence"].update(self_sampled=True),
    lambda x: x.update(current=None),
])
def test_validate_context_rejects_new_fields_outcomes_enums_and_fake_evidence(mutation):
    context = evidence.extract(example())["context"]
    mutation(context)
    with pytest.raises(ValueError):
        evidence.validate_context(context)
